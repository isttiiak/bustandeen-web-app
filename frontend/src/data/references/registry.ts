// The reference map: every Quran verse, hadith, scholarly work, fiqh
// position and data source the app relies on, with why it is cited. It is
// the source of /references (and /references.json for the native app).
//
// Adding a reference anywhere in the code? Add it here too: the reference
// scan (references.test.ts) fails on any citation this list does not know,
// and lists where every entry is used (usage.generated.json). Run
// `npm run refs:update --prefix frontend` after editing, then commit.
//
// `desk` is the desk check: the text and number compared with the source
// (hadith: the sunnah.com English and grades via the hadith-api dataset, or
// the sunnah.com page itself; Quran: quran.com Sahih International and the
// bundled Tanzil text). It is not a scholar's review. Manual checks (you at
// the source, or a scholar) live in manualChecks.json.

export type RefKind = 'quran' | 'hadith' | 'scholarly' | 'fiqh' | 'data';

/**
 * verified   number, wording and grade match the source
 * corrected  this audit fixed the number, wording or grade (see deskNote)
 * weak       a weak narration, shown only with its weak grade
 * unverified could not be fully checked automatically: needs a manual check
 */
export type DeskResult = 'verified' | 'corrected' | 'weak' | 'unverified';

export interface ReferenceEntry {
  /** Stable id: `bukhari:998`, `quran:2:255`, `fiqh:qasr-distance`… */
  id: string;
  kind: RefKind;
  /** How the reference is written out. */
  citation: string;
  url?: string;
  /** The grade, with who graded it. Quran: "Quran". */
  grade?: string;
  /** What the app uses it for. */
  purpose: string;
  desk: DeskResult;
  deskNote?: string;
  /** Date of the desk check, when it is not the audit date below. */
  deskDate?: string;
  /** Other ids the scan may find for this entry (sub-ranges, mirror links). */
  aliases?: string[];
  /** Literal text that marks a use, for entries without a numbered citation. */
  match?: string[];
}

